"""Shared helpers for the Clean The Moon! headless Blender asset scripts.

Original work (M0-W0-T06). Run only as:
    blender --background --python <asset script> -- --out <raw.glb> --report <report.json> --texdir <dir>

Nothing here downloads or reads external art: every vertex and texel is generated by code.
Blender images and Blender UVs both have their origin at the bottom-left, so arrays in this file use
row 0 = bottom (v = 0). The glTF exporter flips V for both consistently.
"""

import argparse
