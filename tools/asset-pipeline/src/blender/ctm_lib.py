# ----------------------------------------------------------------------------------------------- CLI


def cli_args(extra=None):
    argv = sys.argv[sys.argv.index("--") + 1 :] if "--" in sys.argv else []
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", required=True, help="raw (uncompressed) .glb output path")
    parser.add_argument("--report", required=True, help="JSON report path (metrics + step timings)")
    parser.add_argument("--texdir", required=True, help="folder for generated/baked PNG textures")
    parser.add_argument("--seed", type=int, default=1)
    if extra:
        extra(parser)
    args = parser.parse_args(argv)
    # Blender resolves relative image paths against the (unsaved) .blend, so make every path absolute.
    args.out = os.path.abspath(args.out)
    args.report = os.path.abspath(args.report)
    args.texdir = os.path.abspath(args.texdir)
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    os.makedirs(args.texdir, exist_ok=True)
    return args


class Steps:
    """Wall-clock step timer; the build log and the throughput report read it."""

    def __init__(self):
        self.items = []
        self._t = time.perf_counter()
        self._t0 = self._t

    def mark(self, name):
        now = time.perf_counter()
        self.items.append({"step": name, "seconds": round(now - self._t, 3)})
        print(f"[ctm] step {name}: {now - self._t:.2f}s", flush=True)
        self._t = now

    def total(self):
        return round(time.perf_counter() - self._t0, 3)


def write_report(path, data):
    with open(path, "w", encoding="utf-8") as handle:
        json.dump(data, handle, indent=2, sort_keys=True)
        handle.write("\n")


# --------------------------------------------------------------------------------------------- scene


def reset_scene():
    bpy.ops.wm.read_factory_settings(use_empty=True)
    scene = bpy.context.scene
    scene.render.engine = "CYCLES"
    scene.cycles.device = "CPU"
    scene.cycles.samples = 32
    scene.cycles.use_denoising = False
    scene.cycles.seed = 0
    scene.render.bake.margin = 8
    return scene


def object_from_bmesh(name, bm):
    mesh = bpy.data.meshes.new(name)
    bm.to_mesh(mesh)
    bm.free()
    obj = bpy.data.objects.new(name, mesh)
    bpy.context.scene.collection.objects.link(obj)
    return obj


def select_only(active, others=()):
    bpy.context.view_layer.update()
    for obj in bpy.context.scene.objects:
        obj.select_set(False)
    for obj in others:
        obj.select_set(True)
    active.select_set(True)
    bpy.context.view_layer.objects.active = active


def apply_modifiers(obj):
    """Bake the modifier stack into the mesh without bpy.ops (safe in background mode)."""
    bpy.context.view_layer.update()
    depsgraph = bpy.context.evaluated_depsgraph_get()
    evaluated = obj.evaluated_get(depsgraph)
    mesh = bpy.data.meshes.new_from_object(evaluated, preserve_all_data_layers=True, depsgraph=depsgraph)
    old = obj.data
    obj.modifiers.clear()
    obj.data = mesh
    mesh.name = old.name
    bpy.data.meshes.remove(old)


def triangulate(obj):
    bm = bmesh.new()
    bm.from_mesh(obj.data)
    bmesh.ops.triangulate(bm, faces=bm.faces[:])
    bm.to_mesh(obj.data)
    bm.free()


def shade(obj, sharp_angle_deg=None, weighted=False):
    """Smooth faces; optionally mark edges sharper than the angle and apply face-area weighted normals."""
    mesh = obj.data
    bm = bmesh.new()
    bm.from_mesh(mesh)
    limit = math.radians(sharp_angle_deg) if sharp_angle_deg is not None else None
    for face in bm.faces:
        face.smooth = True
    for edge in bm.edges:
        if limit is not None and len(edge.link_faces) == 2:
            edge.smooth = edge.calc_face_angle(0.0) < limit
        else:
            edge.smooth = True
    bm.to_mesh(mesh)
    bm.free()
    if weighted:
        mod = obj.modifiers.new("WeightedNormal", "WEIGHTED_NORMAL")
        mod.keep_sharp = True
        mod.mode = "FACE_AREA"
        mod.weight = 50
        apply_modifiers(obj)


def triangle_count(obj):
    obj.data.calc_loop_triangles()
    return len(obj.data.loop_triangles)


def bounds(obj):
    xs = [v.co.x for v in obj.data.vertices]
    ys = [v.co.y for v in obj.data.vertices]
    zs = [v.co.z for v in obj.data.vertices]
    return [min(xs), min(ys), min(zs)], [max(xs), max(ys), max(zs)]


def decimated_copy(obj, name, target_tris):
    """Collapse-decimated copy (UVs and normals are interpolated) for the LOD chain."""
    copy = obj.copy()
    copy.data = obj.data.copy()
    copy.name = name
    copy.data.name = name
    bpy.context.scene.collection.objects.link(copy)
    current = triangle_count(copy)
    mod = copy.modifiers.new("Decimate", "DECIMATE")
    mod.decimate_type = "COLLAPSE"
    mod.ratio = min(1.0, target_tris / max(1, current))
    mod.use_collapse_triangulate = True
    apply_modifiers(copy)
    return copy


# ------------------------------------------------------------------------------------------ textures


def write_png(path, pixels8):
    """Deterministic RGB/gray 8-bit PNG writer (Sub filter, zlib 9). pixels8: HxWxC uint8, row 0 = TOP."""
    height, width, channels = pixels8.shape
    color_type = {1: 0, 3: 2, 4: 6}[channels]
    raw = pixels8.astype(np.uint8)
    filtered = raw.copy()
    filtered[:, 1:, :] = raw[:, 1:, :] - raw[:, :-1, :]
    rows = np.empty((height, 1 + width * channels), np.uint8)
    rows[:, 0] = 1
    rows[:, 1:] = filtered.reshape(height, width * channels)

    def chunk(tag, data):
        body = tag + data
        return struct.pack(">I", len(data)) + body + struct.pack(">I", zlib.crc32(body) & 0xFFFFFFFF)

    header = struct.pack(">IIBBBBB", width, height, 8, color_type, 0, 0, 0)
    blob = b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", header) + chunk(b"IDAT", zlib.compress(rows.tobytes(), 9)) + chunk(b"IEND", b"")
    with open(path, "wb") as handle:
        handle.write(blob)
    return len(blob)


def save_texture(name, array, srgb, path):
    """array: HxWx3 float 0..1 with row 0 = bottom (Blender convention). Writes a PNG and loads it."""
    pixels8 = np.clip(np.rint(array * 255.0), 0, 255).astype(np.uint8)[::-1]
    size = write_png(path, pixels8)
    image = bpy.data.images.load(path)
    image.name = name
    image.colorspace_settings.name = "sRGB" if srgb else "Non-Color"
    return image, size


def bake_target(name, size, srgb, fill):
    image = bpy.data.images.new(name, size, size, alpha=False, float_buffer=False)
    image.colorspace_settings.name = "sRGB" if srgb else "Non-Color"
    image.generated_color = fill
    return image


def image_array(image):
    """HxWx3 float array, row 0 = bottom. For 8-bit images the values are in the image's own colour space."""
    width, height = image.size
    flat = np.empty(width * height * 4, np.float32)
    image.pixels.foreach_get(flat)
    return flat.reshape(height, width, 4)[..., :3].copy()


def bake_selected_to_active(low, high, material, image, bake_type, samples, extrusion, pass_filter=None):
    scene = bpy.context.scene
    scene.cycles.samples = samples
    nodes = material.node_tree.nodes
    node = nodes.get("BakeTarget") or nodes.new("ShaderNodeTexImage")
    node.name = "BakeTarget"
    node.image = image
    for other in nodes:
        other.select = False
    node.select = True
    nodes.active = node
    select_only(low, [high])
    kwargs = dict(
        type=bake_type,
        use_selected_to_active=True,
        cage_extrusion=extrusion,
        max_ray_distance=extrusion * 4.0,
        margin=8,
        use_clear=True,
    )
    if bake_type == "NORMAL":
        kwargs["normal_space"] = "TANGENT"
    if pass_filter:
        kwargs["pass_filter"] = pass_filter
    bpy.ops.object.bake(**kwargs)
    return image_array(image)


def bake_vertex_ao(obj, samples=64, attribute="Color"):
    """Cycles AO baked to a per-corner colour attribute; exported as glTF COLOR_0."""
    mesh = obj.data
    if attribute not in mesh.color_attributes:
        mesh.color_attributes.new(attribute, "BYTE_COLOR", "CORNER")
    layer = mesh.color_attributes[attribute]
    mesh.color_attributes.active_color = layer
    mesh.color_attributes.render_color_index = list(mesh.color_attributes).index(layer)
    scene = bpy.context.scene
    scene.cycles.samples = samples
    scene.render.bake.target = "VERTEX_COLORS"
    select_only(obj)
    bpy.ops.object.bake(type="AO", use_selected_to_active=False, target="VERTEX_COLORS")
    scene.render.bake.target = "IMAGE_TEXTURES"
    # Soften: buried vertices bake to black, which is too heavy once multiplied into the base colour.
    count = len(mesh.loops)
    colors = np.empty(count * 4, np.float32)
    layer.data.foreach_get("color", colors)
    colors = colors.reshape(count, 4)
    occlusion = np.clip(colors[:, 0], 0.0, 1.0)
    occlusion = 0.35 + 0.65 * occlusion**0.8
    colors[:, 0] = colors[:, 1] = colors[:, 2] = occlusion
    colors[:, 3] = 1.0
    layer.data.foreach_set("color", colors.ravel())
    mesh.update()


def ensure_world(ao_distance=0.8):
    world = bpy.data.worlds.new("ctm_world")
    bpy.context.scene.world = world
    world.light_settings.distance = ao_distance
    return world


# ----------------------------------------------------------------------------------------- materials


def gltf_output_group():
    """The node group the Blender glTF exporter reads the occlusion input from."""
    name = "glTF Material Output"
    group = bpy.data.node_groups.get(name)
    if group is None:
        group = bpy.data.node_groups.new(name, "ShaderNodeTree")
        group.interface.new_socket(name="Occlusion", in_out="INPUT", socket_type="NodeSocketFloat")
        group.nodes.new("NodeGroupInput")
    return group


def pbr_material(name, base=None, normal=None, orm=None, emissive=None, vertex_ao=False):
    """Principled material wired the way the glTF exporter packs it: base colour, normal, ORM, emissive."""
    material = bpy.data.materials.new(name)
    material.use_nodes = True
    tree = material.node_tree
    nodes, links = tree.nodes, tree.links
    bsdf = nodes.get("Principled BSDF")
    bsdf.inputs["Roughness"].default_value = 0.9
    bsdf.inputs["Metallic"].default_value = 0.0

    def tex(image, label):
        node = nodes.new("ShaderNodeTexImage")
        node.image = image
        node.label = label
        return node

    if base is not None:
        base_node = tex(base, "BaseColor")
        if vertex_ao:
            ao = nodes.new("ShaderNodeVertexColor")
            mix = nodes.new("ShaderNodeMix")
            mix.data_type = "RGBA"
            mix.blend_type = "MULTIPLY"
            mix.inputs[0].default_value = 1.0
            links.new(base_node.outputs["Color"], mix.inputs[6])
            links.new(ao.outputs["Color"], mix.inputs[7])
            links.new(mix.outputs[2], bsdf.inputs["Base Color"])
        else:
            links.new(base_node.outputs["Color"], bsdf.inputs["Base Color"])
    if normal is not None:
        normal_tex = tex(normal, "Normal")
        normal_map = nodes.new("ShaderNodeNormalMap")
        links.new(normal_tex.outputs["Color"], normal_map.inputs["Color"])
        links.new(normal_map.outputs["Normal"], bsdf.inputs["Normal"])
    if orm is not None:
        orm_tex = tex(orm, "ORM")
        split = nodes.new("ShaderNodeSeparateColor")
        links.new(orm_tex.outputs["Color"], split.inputs["Color"])
        links.new(split.outputs["Green"], bsdf.inputs["Roughness"])
        links.new(split.outputs["Blue"], bsdf.inputs["Metallic"])
        out = nodes.new("ShaderNodeGroup")
        out.node_tree = gltf_output_group()
        links.new(split.outputs["Red"], out.inputs["Occlusion"])
    if emissive is not None:
        emissive_tex = tex(emissive, "Emissive")
        links.new(emissive_tex.outputs["Color"], bsdf.inputs["Emission Color"])
        bsdf.inputs["Emission Strength"].default_value = 1.0
    return material


def assign_material(obj, material):
    obj.data.materials.clear()
    obj.data.materials.append(material)


# -------------------------------------------------------------------------------------------- export


def export_glb(path, objects, vertex_color=False):
    select_only(objects[0], objects)
    bpy.ops.export_scene.gltf(
        filepath=path,
        export_format="GLB",
        use_selection=True,
        export_apply=True,
        export_yup=True,
        export_texcoords=True,
        export_normals=True,
        export_tangents=True,
        export_materials="EXPORT",
        export_image_format="AUTO",
        export_vertex_color="ACTIVE" if vertex_color else "NONE",
        export_all_vertex_colors=False,
        export_extras=True,
        export_cameras=False,
        export_lights=False,
        export_animations=False,
    )
    return os.path.getsize(path)


def texel_density(obj, tex_w, tex_h):
    """Area-weighted texel density statistics (px per metre) over all triangles."""
    mesh = obj.data
    mesh.calc_loop_triangles()
    uv = mesh.uv_layers.active.data
    densities, areas = [], []
    for tri in mesh.loop_triangles:
        if tri.area <= 1e-10:
            continue
        a, b, c = (uv[i].uv for i in tri.loops)
        uv_area = abs((b.x - a.x) * (c.y - a.y) - (c.x - a.x) * (b.y - a.y)) * 0.5
        densities.append(math.sqrt(uv_area * tex_w * tex_h / tri.area))
        areas.append(tri.area)
    densities = np.array(densities)
    areas = np.array(areas)
    order = np.argsort(densities)
    cumulative = np.cumsum(areas[order]) / areas.sum()

    def percentile(p):
        return float(densities[order][np.searchsorted(cumulative, p)])

    return {
        "areaM2": round(float(areas.sum()), 3),
        "areaShareAtLeast256": round(float(areas[densities >= 256.0].sum() / areas.sum()), 4),
        "areaShareAtLeast512": round(float(areas[densities >= 512.0].sum() / areas.sum()), 4),
        "p05": round(percentile(0.05), 1),
        "median": round(percentile(0.5), 1),
        "mean": round(float((densities * areas).sum() / areas.sum()), 1),
    }
