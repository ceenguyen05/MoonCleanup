"""Production character / tool kit (M1-W4-T07): the blockout kit plus UVs, skin bones and the numeral glyph atlas.

Original work for Clean The Moon!; every vertex and texel is generated by code. Extends `ctm_blockout.Builder`
(slot / part per face in COLOR_0, see that module) with:

- a skin bone per face (`bone` context): every vertex belongs to exactly one bone, weight 1 (rigid skinning; the
  runtime shader's COLOR_0.B part is the same partition at a coarser level, so skin and shader agree in bind pose);
- per-corner UVs (TEXCOORD_0), only meaningful on decal patches (the numeral glyph); every other face sits at
  UV (0, 0), a cell corner of the glyph atlas that is empty;
- an armature built from a bone table, vertex groups per bone, and a GLB export with skins, UVs and COLOR_0;
- the 512 x 512 numeral glyph atlas (P01..P16 -> numerals 1..16, 4 x 4 cells of 128 px), a signed-distance mask so
  the shader's threshold stays crisp at every distance and survives block compression.

Coordinates are Blender's (Z up, character facing -Y); the glTF exporter turns them into Y up, facing +Z.
"""

import math
import os

import bpy
import numpy as np
from mathutils import Vector

import ctm_blockout as kit
import ctm_lib as lib


class ProdBuilder(kit.Builder):
    """Blockout builder with a skin bone per face and optional per-corner UVs."""

    def __init__(self, name):
        super().__init__(name)
        self.face_bone = []
        self.face_uv = []
        self.bone = "pelvis"

    def _append(self, verts, faces, slot, part, closed, outward=None):
        before = len(self.faces)
        super()._append(verts, faces, slot, part, closed, outward)
        added = len(self.faces) - before
        self.face_bone.extend([self.bone] * added)
        self.face_uv.extend([None] * added)

    def add_decal(self, fn, nu, nv, slot, outward, part=0):
        """Open grid fn(u, v) -> (x, y, z) like `add_patch`, with UV = (u, v) per corner (Blender: v up)."""
        verts = [tuple(fn(i / nu, j / nv)) for j in range(nv + 1) for i in range(nu + 1)]
        uvs = [(i / nu, j / nv) for j in range(nv + 1) for i in range(nu + 1)]
        faces = []
        for j in range(nv):
            for i in range(nu):
                k = j * (nu + 1) + i
                faces.append([k, k + 1, k + nu + 2, k + nu + 1])
        base = len(self.verts)
        before = len(self.faces)
        self._append(verts, faces, slot, part, closed=False, outward=outward)
        # `_append` may have reversed a face's winding; look the UV up by vertex index so the order does not matter.
        for f in range(before, len(self.faces)):
            self.face_uv[f] = [uvs[v - base] for v in self.faces[f]]

    def to_object(self, name, material):
        obj = super().to_object(name, material)
        mesh = obj.data
        layer = mesh.uv_layers.new(name="UVMap")
        coords = np.zeros((len(mesh.loops), 2), np.float32)
        for poly in mesh.polygons:
            uv = self.face_uv[poly.index]
            if uv is None:
                continue
            for corner, li in enumerate(poly.loop_indices):
                coords[li] = uv[corner]
        layer.data.foreach_set("uv", coords.ravel())
        return obj


