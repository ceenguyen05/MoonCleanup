def build_armature(name, bones):
    """bones: list of (name, parent or None, head xyz, tail xyz). Returns the armature object (rest pose)."""
    data = bpy.data.armatures.new(name)
    arm = bpy.data.objects.new(name, data)
    bpy.context.scene.collection.objects.link(arm)
    bpy.context.view_layer.objects.active = arm
    for other in bpy.context.scene.objects:
        other.select_set(False)
    arm.select_set(True)
    bpy.ops.object.mode_set(mode="EDIT")
    made = {}
    for bone_name, parent, head, tail in bones:
        eb = data.edit_bones.new(bone_name)
        eb.head = Vector(head)
        eb.tail = Vector(tail)
        eb.roll = 0.0
        eb.use_deform = True
        if parent is not None:
            eb.parent = made[parent]
            eb.use_connect = False
        made[bone_name] = eb
    bpy.ops.object.mode_set(mode="OBJECT")
    return arm


def skin_to(obj, builder, arm):
    """One vertex group per bone (weight 1 from the face's bone), Armature modifier, parented to the armature."""
    mesh = obj.data
    groups = {}
    members = {}
    for poly in mesh.polygons:
        bone = builder.face_bone[poly.index]
        members.setdefault(bone, set()).update(poly.vertices)
    for bone_name in [b.name for b in arm.data.bones]:
        groups[bone_name] = obj.vertex_groups.new(name=bone_name)
    for bone_name, verts in members.items():
        groups[bone_name].add(sorted(verts), 1.0, "REPLACE")
    mod = obj.modifiers.new("Armature", "ARMATURE")
    mod.object = arm
    obj.parent = arm
    return {b: len(v) for b, v in members.items()}


def export_skinned_glb(path, objects):
    """GLB with COLOR_0 (slot / AO / part), TEXCOORD_0, the skin and empties (sockets) as nodes."""
    bpy.context.view_layer.update()
    for other in bpy.context.scene.objects:
        other.select_set(False)
    for obj in objects:
        obj.select_set(True)
    bpy.context.view_layer.objects.active = objects[0]
    bpy.ops.export_scene.gltf(
        filepath=path,
        export_format="GLB",
        use_selection=True,
        export_apply=True,
        export_yup=True,
        export_texcoords=True,
        export_normals=True,
        export_tangents=False,
        export_materials="EXPORT",
        export_image_format="AUTO",
        export_vertex_color="ACTIVE",
        export_all_vertex_colors=False,
        export_extras=True,
        export_cameras=False,
        export_lights=False,
        export_animations=False,
        export_skins=True,
        export_def_bones=False,
        export_influence_nb=4,
    )
    return os.path.getsize(path)


# ------------------------------------------------------------------------------------------- glyph atlas


def _arc(cx, cy, rx, ry, a0, a1, n=10):
    return [(cx + rx * math.cos(math.radians(a0 + (a1 - a0) * i / n)), cy + ry * math.sin(math.radians(a0 + (a1 - a0) * i / n))) for i in range(n + 1)]


# Stencil-style numeral strokes in a unit box (x 0..1, y 0..1, y up). Original letterforms: round bowls, flat bars.
DIGITS = {
    "0": [_arc(0.5, 0.5, 0.3, 0.4, 0, 360, 24)],
    "1": [[(0.32, 0.78), (0.52, 0.9), (0.52, 0.1)], [(0.3, 0.1), (0.74, 0.1)]],
    "2": [_arc(0.5, 0.66, 0.27, 0.24, 160, -30, 12) + [(0.22, 0.1), (0.8, 0.1)]],
    "3": [_arc(0.5, 0.7, 0.25, 0.2, 150, -90, 12), _arc(0.5, 0.3, 0.28, 0.2, 90, -150, 12)],
    "4": [[(0.62, 0.1), (0.62, 0.9), (0.2, 0.34), (0.82, 0.34)]],
    "5": [[(0.76, 0.9), (0.28, 0.9), (0.25, 0.53)] + _arc(0.5, 0.33, 0.29, 0.23, 120, -150, 14)],
    "6": [_arc(0.5, 0.31, 0.28, 0.21, 0, 360, 18), _arc(0.66, 0.42, 0.44, 0.48, 100, 178, 10)],
    "7": [[(0.2, 0.9), (0.8, 0.9), (0.42, 0.1)]],
    "8": [_arc(0.5, 0.71, 0.23, 0.19, 0, 360, 18), _arc(0.5, 0.29, 0.28, 0.21, 0, 360, 18)],
    "9": [_arc(0.5, 0.69, 0.28, 0.21, 0, 360, 18), _arc(0.34, 0.58, 0.44, 0.48, -80, -2, 10)],
}


def _segments(text):
    """Line segments (x0, y0, x1, y1) of `text` laid out in a unit cell; two digits share the cell side by side."""
    segs = []
    count = len(text)
    width = 0.62 if count == 1 else 0.44
    gap = 0.04
    total = width * count + gap * (count - 1)
    x0 = 0.5 - total / 2.0
    for k, ch in enumerate(text):
        ox = x0 + k * (width + gap)
        for stroke in DIGITS[ch]:
            pts = [(ox + x * width, 0.12 + y * 0.76) for x, y in stroke]
            for a, b in zip(pts, pts[1:]):
                segs.append((a[0], a[1], b[0], b[1]))
    return np.array(segs, np.float64)


def glyph_atlas(path, cell=128, spread_px=10.0, stroke=0.062):
    """512 x 512 RGB PNG: numerals 1..16 in a 4 x 4 grid (row 0 = top row of cells), signed distance mask.

    Value 0.5 is the stroke edge, 1 inside, 0 outside (linear, `spread_px` pixels either side)."""
    size = cell * 4
    out = np.zeros((size, size), np.float64)
    ys, xs = np.mgrid[0:cell, 0:cell]
    px = (xs + 0.5) / cell
    py = 1.0 - (ys + 0.5) / cell  # image row 0 = top; glyph y up
    for i in range(16):
        segs = _segments(str(i + 1))
        ax, ay, bx, by = (segs[:, k][:, None, None] for k in range(4))
        dx, dy = bx - ax, by - ay
        length2 = np.maximum(dx * dx + dy * dy, 1e-12)
        t = np.clip(((px - ax) * dx + (py - ay) * dy) / length2, 0.0, 1.0)
        dist = np.sqrt((px - ax - t * dx) ** 2 + (py - ay - t * dy) ** 2).min(axis=0)
        value = np.clip(0.5 + (stroke - dist) * cell / (2.0 * spread_px), 0.0, 1.0)
        row, col = divmod(i, 4)
        out[row * cell : (row + 1) * cell, col * cell : (col + 1) * cell] = value
    pixels = np.repeat(np.rint(out * 255.0).astype(np.uint8)[:, :, None], 3, axis=2)
    size_bytes = lib.write_png(path, pixels)
    image = bpy.data.images.load(path)
    image.name = "custodian_glyphs"
    image.colorspace_settings.name = "Non-Color"
    return image, size_bytes


def glyph_material(name, glyphs):
    """The exported placeholder material: the glyph atlas rides in the normal slot so the pipeline encodes it as
    linear UASTC (the runtime TSL material reads it as a mask, never as a normal map)."""
    material = bpy.data.materials.new(name)
    material.use_nodes = True
    tree = material.node_tree
    bsdf = tree.nodes.get("Principled BSDF")
    tex = tree.nodes.new("ShaderNodeTexImage")
    tex.image = glyphs
    nmap = tree.nodes.new("ShaderNodeNormalMap")
    tree.links.new(tex.outputs["Color"], nmap.inputs["Color"])
    tree.links.new(nmap.outputs["Normal"], bsdf.inputs["Normal"])
    nmap.inputs["Strength"].default_value = 0.0
    return material


# ------------------------------------------------------------------------------------------------- hand tools

# Tool frame = the custodian's right-hand socket frame (`socket_hand_R`, bind rotation 30 deg about X). The hold pose of
# the W3-T07 poser (shoulder 0.3 + elbow 1.05 rad forward) turns that frame by a further -1.35 rad about X, so in the
# hold pose the tool frame is the custodian frame rotated by HOLD_DEG about X. Long tools are modelled in that
# "hold world" frame (grip at the origin, Z up, forward -Y, ground HOLD_GROUND_Z below the grip) and mapped back into
# the tool frame with `to_tool_frame`, so the broom heads rest on the ground in the hold pose.
HOLD_DEG = 30.0 - math.degrees(0.3 + 1.05)
HOLD_GROUND_Z = -1.05


def to_tool_frame(builder, sockets=()):
    """Rotates a builder's vertices (and socket empties) from the hold world frame into the tool frame."""
    from mathutils import Matrix

    m = Matrix.Rotation(math.radians(-HOLD_DEG), 4, "X")
    builder.verts = [tuple(m @ Vector(v)) for v in builder.verts]
    for s in sockets:
        s.location = m @ s.location
        s.rotation_euler = (m.to_euler()[0] + s.rotation_euler[0], 0.0, 0.0)


def tool_main(asset_id, build, slot_names, sockets_fn, lods=3, hold_frame=False, ao_distance=0.05):
    """Shared tool script body: LOD meshes, vertex AO, sockets, GLB, report."""
    args = lib.cli_args()
    steps = lib.Steps()
    lib.reset_scene()
    lib.ensure_world(ao_distance=ao_distance)
    material = kit.flat_material(asset_id)
    objects = []
    for lod in range(lods):
        builder = build(lod)
        sockets = sockets_fn() if lod == 0 else []
        if hold_frame:
            to_tool_frame(builder, sockets)
        obj = builder.to_object(f"{asset_id}_LOD{lod}", material)
        kit.shade_smooth(obj, 50.0)
        objects.append(obj)
        if lod == 0:
            socket_objs = sockets
    steps.mark("geometry")
    for obj in objects:
        kit.bake_ao_into_green(obj, samples=32, floor=0.55)
    steps.mark("vertex AO")
    size = kit.export_glb(args.out, objects + list(socket_objs))
    steps.mark("export")
    low, top = lib.bounds(objects[0])
    areas = kit.slot_areas(objects[0], slot_names)
    total = sum(areas.values())
    lib.write_report(
        args.report,
        {
            "asset": asset_id,
            "class": "handTool",
            "placeholder": False,
            "sizeM": [round(top[i] - low[i], 4) for i in range(3)],
            "lodTriangles": [lib.triangle_count(o) for o in objects],
            "slotShare": {k: round(v / total, 4) for k, v in areas.items()},
            "sockets": [s.name for s in socket_objs],
            "rawBytes": size,
            "steps": steps.items,
            "totalSeconds": steps.total(),
        },
    )
    print(f"[ctm] {asset_id}: LOD triangles {[lib.triangle_count(o) for o in objects]}", flush=True)
