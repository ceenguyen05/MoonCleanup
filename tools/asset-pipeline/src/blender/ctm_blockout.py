"""Blockout kit (M1-W3-T07): parametric shells with a material slot and a rigid part id per face.

Original work for Clean The Moon!; every vertex is generated by code. Used by the blockout custodian and the
Desk Duster v0 source scripts. Each face carries two integers that the runtime shader reads from glTF COLOR_0:

    R = slot / 15   material slot (palette row in apps/client/src/visuals/characters/blockout/palette.ts)
    G = ambient occlusion (baked per corner by Cycles, softened)
    B = part / 15   rigid part for the procedural motion (0 = body, 1..8 = limb segments)
    A = 1

Both integers survive glTF-Transform's 8-bit colour quantisation exactly (k / 15 * 255 = 17 k).
Coordinates are Blender's (Z up, character facing -Y); the glTF exporter turns them into Y up, facing +Z.
"""

import math
import os

import bmesh
import bpy
import numpy as np
from mathutils import Matrix, Vector

SLOT_SCALE = 15.0


def spow(value, exponent):
    """Signed power: keeps the sign of `value` (superquadric helper)."""
    return math.copysign(abs(value) ** exponent, value)


class Builder:
    """Accumulates shells; each `add_*` call appends one shell with one slot and one part."""

    def __init__(self, name):
        self.name = name
        self.verts = []
        self.faces = []
        self.face_slot = []
        self.face_part = []
        self.shells = []

    # --------------------------------------------------------------------------------------- low level

    def _append(self, verts, faces, slot, part, closed, outward=None):
        """Append a shell; orient its faces outward (signed volume for closed shells, `outward` hint otherwise)."""
        base = len(self.verts)
        points = [Vector(v) for v in verts]
        if closed:
            volume = 0.0
            for face in faces:
                a = points[face[0]]
                for k in range(1, len(face) - 1):
                    volume += a.dot(points[face[k]].cross(points[face[k + 1]]))
            flip = volume < 0.0
        else:
            normal_sum = Vector((0.0, 0.0, 0.0))
            for face in faces:
                a, b, c = points[face[0]], points[face[1]], points[face[2]]
                normal_sum += (b - a).cross(c - a)
            flip = outward is not None and normal_sum.dot(Vector(outward)) < 0.0
        self.verts.extend(tuple(p) for p in points)
        for face in faces:
            ordered = list(reversed(face)) if flip else list(face)
            self.faces.append([base + i for i in ordered])
            self.face_slot.append(slot)
            self.face_part.append(part)
        self.shells.append({"slot": slot, "part": part, "faces": len(faces)})

    # ------------------------------------------------------------------------------------ primitives

    def add_superellipsoid(self, center, half, slot, part=0, e_h=2.0, e_v=2.0, nu=24, nv=12, matrix=None, z_range=None):
        """Superquadric: e = 2 is an ellipsoid, larger e is boxier (rounded-rect shells).

        `z_range` = (v0, v1) in -1..1 keeps only part of the latitude range (open shell, capped flat)."""
        a, b, c = half
        v_lo, v_hi = (-1.0, 1.0) if z_range is None else z_range
        rings = []
        for j in range(1, nv):
            t = v_lo + (v_hi - v_lo) * j / nv
            phi = t * math.pi / 2.0
            rings.append(phi)
        verts = []
        faces = []
        pe_h, pe_v = 2.0 / e_h, 2.0 / e_v
        for phi in rings:
            cp, sp = math.cos(phi), math.sin(phi)
            for i in range(nu):
                th = 2.0 * math.pi * i / nu
                x = a * spow(cp, pe_v) * spow(math.cos(th), pe_h)
                y = b * spow(cp, pe_v) * spow(math.sin(th), pe_h)
                z = c * spow(sp, pe_v)
                verts.append((x, y, z))
        for j in range(len(rings) - 1):
            for i in range(nu):
                i1 = (i + 1) % nu
                faces.append([j * nu + i, j * nu + i1, (j + 1) * nu + i1, (j + 1) * nu + i])
        # Caps: a pole point (full range) or a flat fan at the clipped latitude.
        bottom_z = c * spow(math.sin(v_lo * math.pi / 2.0), pe_v) if z_range else -c
        top_z = c * spow(math.sin(v_hi * math.pi / 2.0), pe_v) if z_range else c
        bottom = len(verts)
        verts.append((0.0, 0.0, bottom_z))
        top = len(verts)
        verts.append((0.0, 0.0, top_z))
        last = (len(rings) - 1) * nu
        for i in range(nu):
            i1 = (i + 1) % nu
            faces.append([bottom, i1, i])
            faces.append([top, last + i, last + i1])
        self._finish(verts, faces, center, matrix, slot, part, closed=True)

    def add_tube(self, points, radii, slot, part=0, nu=16, cap_rings=3, flatten=1.0, caps=(True, True)):
        """Loft through `points` (Blender coords) with circular sections of `radii`; hemispherical end caps.

        `flatten` < 1 squashes the section along the second frame axis (oval limbs)."""
        pts = [Vector(p) for p in points]
        frames = []
        for k, p in enumerate(pts):
            d = (pts[min(k + 1, len(pts) - 1)] - pts[max(k - 1, 0)]).normalized()
            ref = Vector((1.0, 0.0, 0.0)) if abs(d.x) < 0.9 else Vector((0.0, 1.0, 0.0))
            n1 = d.cross(ref).normalized()
            n2 = d.cross(n1).normalized()
            frames.append((d, n1, n2))
        sections = []  # (center, radius, d, n1, n2)
        d0, n10, n20 = frames[0]
        if caps[0]:
            for r in range(cap_rings, 0, -1):
                ang = (math.pi / 2.0) * r / (cap_rings + 1)
                sections.append((pts[0] - d0 * radii[0] * math.sin(ang), radii[0] * math.cos(ang), d0, n10, n20))
        for k, p in enumerate(pts):
            d, n1, n2 = frames[k]
            sections.append((p, radii[k], d, n1, n2))
        d1, n11, n21 = frames[-1]
        if caps[1]:
            for r in range(1, cap_rings + 1):
                ang = (math.pi / 2.0) * r / (cap_rings + 1)
                sections.append((pts[-1] + d1 * radii[-1] * math.sin(ang), radii[-1] * math.cos(ang), d1, n11, n21))
        verts = []
        faces = []
        for center, radius, _, n1, n2 in sections:
            for i in range(nu):
                th = 2.0 * math.pi * i / nu
                verts.append(tuple(center + n1 * (radius * math.cos(th)) + n2 * (radius * flatten * math.sin(th))))
        count = len(sections)
        for j in range(count - 1):
            for i in range(nu):
                i1 = (i + 1) % nu
                faces.append([j * nu + i, j * nu + i1, (j + 1) * nu + i1, (j + 1) * nu + i])
        # Cap centre: the hemisphere tip, or the flat end of the section when the end is uncapped.
        first_c = pts[0] - d0 * radii[0] if caps[0] else pts[0]
        last_c = pts[-1] + d1 * radii[-1] if caps[1] else pts[-1]
        a = len(verts)
        verts.append(tuple(first_c))
        b = len(verts)
        verts.append(tuple(last_c))
        last = (count - 1) * nu
        for i in range(nu):
            i1 = (i + 1) % nu
            faces.append([a, i1, i])
            faces.append([b, last + i, last + i1])
        self._finish(verts, faces, (0.0, 0.0, 0.0), None, slot, part, closed=True)

    def add_torus(self, center, radius, minor, slot, part=0, nu=32, nv=8, scale=(1.0, 1.0), matrix=None):
        """Ring around local Z; `scale` stretches the major circle into an ellipse (x, y)."""
        verts = []
        faces = []
        for i in range(nu):
            th = 2.0 * math.pi * i / nu
            cx, cy = math.cos(th) * radius * scale[0], math.sin(th) * radius * scale[1]
            out = Vector((math.cos(th) * scale[1], math.sin(th) * scale[0], 0.0)).normalized()
            for j in range(nv):
                ph = 2.0 * math.pi * j / nv
                p = Vector((cx, cy, 0.0)) + out * (minor * math.cos(ph)) + Vector((0.0, 0.0, minor * math.sin(ph)))
                verts.append(tuple(p))
        for i in range(nu):
            i1 = (i + 1) % nu
            for j in range(nv):
                j1 = (j + 1) % nv
                faces.append([i * nv + j, i1 * nv + j, i1 * nv + j1, i * nv + j1])
        self._finish(verts, faces, center, matrix, slot, part, closed=True)

    def add_patch(self, fn, nu, nv, slot, outward, part=0):
        """Open grid surface fn(u, v) -> (x, y, z), u, v in 0..1; faces oriented toward `outward`."""
        verts = [tuple(fn(i / nu, j / nv)) for j in range(nv + 1) for i in range(nu + 1)]
        faces = []
        for j in range(nv):
            for i in range(nu):
                k = j * (nu + 1) + i
                faces.append([k, k + 1, k + nu + 2, k + nu + 1])
        self._append(verts, faces, slot, part, closed=False, outward=outward)

    def _finish(self, verts, faces, center, matrix, slot, part, closed):
        m = matrix if matrix is not None else Matrix.Identity(4)
        c = Vector(center)
        moved = [tuple(m @ Vector(v) + c) for v in verts]
        self._append(moved, faces, slot, part, closed)

    # ---------------------------------------------------------------------------------------- output

    def triangle_count(self):
        return sum(len(f) - 2 for f in self.faces)

    def to_object(self, name, material):
        mesh = bpy.data.meshes.new(name)
        mesh.from_pydata(self.verts, [], self.faces)
        mesh.update()
        obj = bpy.data.objects.new(name, mesh)
        bpy.context.scene.collection.objects.link(obj)
        obj.data.materials.append(material)
        layer = mesh.color_attributes.new("Col", "FLOAT_COLOR", "CORNER")
        colors = np.zeros((len(mesh.loops), 4), np.float32)
        for poly in mesh.polygons:
            slot = self.face_slot[poly.index] / SLOT_SCALE
            part = self.face_part[poly.index] / SLOT_SCALE
            for li in poly.loop_indices:
                colors[li] = (slot, 1.0, part, 1.0)
        layer.data.foreach_set("color", colors.ravel())
        mesh.color_attributes.active_color = layer
        mesh.color_attributes.render_color_index = list(mesh.color_attributes).index(layer)
        mesh.update()
        return obj


def shade_smooth(obj, sharp_deg=48.0):
    """Smooth shading with edges above `sharp_deg` kept sharp (rounded shells read soft, rims stay crisp)."""
    mesh = obj.data
    bm = bmesh.new()
    bm.from_mesh(mesh)
    limit = math.radians(sharp_deg)
    for face in bm.faces:
        face.smooth = True
    for edge in bm.edges:
        edge.smooth = not (len(edge.link_faces) == 2 and edge.calc_face_angle(0.0) > limit)
    bm.to_mesh(mesh)
    bm.free()
    mesh.update()


def bake_ao_into_green(obj, samples=48, floor=0.45):
    """Cycles AO to a temporary corner attribute, softened, then copied into COLOR_0.G."""
    mesh = obj.data
    data = mesh.color_attributes["Col"]
    tmp = mesh.color_attributes.new("AO", "FLOAT_COLOR", "CORNER")
    mesh.color_attributes.active_color = tmp
    mesh.color_attributes.render_color_index = list(mesh.color_attributes).index(tmp)
    scene = bpy.context.scene
    scene.cycles.samples = samples
    scene.render.bake.target = "VERTEX_COLORS"
    bpy.context.view_layer.update()
    for other in bpy.context.scene.objects:
        other.select_set(False)
    obj.select_set(True)
    bpy.context.view_layer.objects.active = obj
    bpy.ops.object.bake(type="AO", use_selected_to_active=False, target="VERTEX_COLORS")
    scene.render.bake.target = "IMAGE_TEXTURES"
    count = len(mesh.loops)
    ao = np.empty(count * 4, np.float32)
    mesh.color_attributes["AO"].data.foreach_get("color", ao)
    occlusion = np.clip(ao.reshape(count, 4)[:, 0], 0.0, 1.0)
    occlusion = floor + (1.0 - floor) * occlusion**0.75
    cols = np.empty(count * 4, np.float32)
    data = mesh.color_attributes["Col"]
    data.data.foreach_get("color", cols)
    cols = cols.reshape(count, 4)
    cols[:, 1] = occlusion
    data.data.foreach_set("color", cols.ravel())
    mesh.color_attributes.remove(mesh.color_attributes["AO"])
    data = mesh.color_attributes["Col"]
    mesh.color_attributes.active_color = data
    mesh.color_attributes.render_color_index = list(mesh.color_attributes).index(data)
    mesh.update()


def flat_material(name):
    """One plain material per asset (the runtime replaces it with the TSL custodian material)."""
    material = bpy.data.materials.new(name)
    material.use_nodes = True
    bsdf = material.node_tree.nodes.get("Principled BSDF")
    bsdf.inputs["Roughness"].default_value = 0.7
    return material


def add_socket(name, location, rotation_x_deg=0.0):
    """Empty exported as a glTF node (sockets and pivots); identity frame = asset frame."""
    empty = bpy.data.objects.new(name, None)
    empty.empty_display_size = 0.05
    empty.location = location
    empty.rotation_euler = (math.radians(rotation_x_deg), 0.0, 0.0)
    bpy.context.scene.collection.objects.link(empty)
    return empty


def slot_areas(obj, slots):
    """Surface area per slot id (m^2), for the palette-share report."""
    mesh = obj.data
    layer = mesh.color_attributes["Col"]
    areas = {}
    for poly in mesh.polygons:
        slot = int(round(layer.data[poly.loop_indices[0]].color[0] * SLOT_SCALE))
        name = slots.get(slot, str(slot))
        areas[name] = areas.get(name, 0.0) + poly.area
    return {k: round(v, 5) for k, v in sorted(areas.items())}


def export_glb(path, objects):
    """GLB with COLOR_0 (the data attribute), no UVs or tangents, empties as nodes."""
    bpy.context.view_layer.update()
    for other in bpy.context.scene.objects:
        other.select_set(False)
    for obj in objects:
        obj.select_set(True)
    bpy.context.view_layer.objects.active = objects[0]
    bpy.ops.export_scene.gltf(
        filepath=path,
        export_format="GLB",
        use_selection=True,
        export_apply=True,
        export_yup=True,
        export_texcoords=False,
        export_normals=True,
        export_tangents=False,
        export_materials="EXPORT",
        export_vertex_color="ACTIVE",
        export_all_vertex_colors=False,
        export_extras=True,
        export_cameras=False,
        export_lights=False,
        export_animations=False,
    )
    return os.path.getsize(path)
