import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { decodePng, fullRect, type Img, type Rect } from "./image";
import {
  edgeWidth1090,
  labB,
  lumaPatch,
  nonBlackFraction,
  pngDiskSize,
  sobelSharpness,
  starCount,
  temporalVariance,
} from "./measures";
import { frameRois, measureRois, type RoiResult, type RoiSpec } from "./rois";

export interface MeasureResults {
  readonly lumaMean: { value: number; rect: Rect };
  readonly sobel: { value: number; rect: Rect };
  readonly labB: { value: number; rect: Rect };
  readonly edgeWidth1090: { value: number | null; rect: Rect };
  readonly stars: { value: number; rect: Rect };
  readonly nonBlackFraction: number;
  readonly diskBytes: number;
  readonly temporalVariance?: { value: number; rect: Rect; frames: number };
  /** Per-region measures: frame layout regions plus the scene's own probes (chips, edge lines, world points). */
  readonly rois?: Record<string, RoiResult>;
}

/**
 * Whole-frame default measurements. Scene-specific patches (albedo chart, stroke edge) are added by the
 * visual-qa-reviewer's scene list via `patches`; they land in the same sidecar under `patches`.
 */
export function measureImage(
  png: Uint8Array,
  img: Img = decodePng(png),
  edgeRect?: Rect,
  rois?: readonly RoiSpec[],
): MeasureResults {
  const all = fullRect(img);
  // A whole-frame 10-90 edge is meaningless (rows mix many features): only computed over an explicit rect, else null.
  const edge = edgeRect === undefined ? null : edgeWidth1090(img, edgeRect);
  return {
    lumaMean: lumaPatch(img, all),
    sobel: sobelSharpness(img, all),
    labB: labB(img, all),
    edgeWidth1090: {
      value: edge !== null && Number.isFinite(edge.value) ? edge.value : null,
      rect: edge?.rect ?? { x: 0, y: 0, w: 0, h: 0 },
    },
    stars: starCount(img, all),
    nonBlackFraction: nonBlackFraction(img),
    diskBytes: pngDiskSize(png),
    rois: measureRois(img, [...frameRois(img.width, img.height), ...(rois ?? [])]),
  };
}

/** Mean of the `edge1090Px` values of the `line:*` ROIs (null when none has an edge). */
export function lineEdgeSummary(m: MeasureResults | undefined): string {
  if (m?.rois === undefined) return "n/a";
  const parts: string[] = [];
  for (const [name, r] of Object.entries(m.rois)) {
    if (r.kind === "line" && r.edge1090Px !== null)
      parts.push(`${name.replace("line:", "")} ${r.edge1090Px.toFixed(1)}`);
  }
  return parts.length ? parts.join(" / ") : "n/a";
}

export function measureSequence(frames: readonly Img[]): { value: number; rect: Rect; frames: number } {
  const t = temporalVariance(frames);
  return { ...t, frames: frames.length };
}

/** Add measure results to an existing sidecar JSON next to a PNG. Returns the merged sidecar. */
export function measureIntoSidecar(pngPath: string, edgeRect?: Rect): Record<string, unknown> {
  const jsonPath = pngPath.replace(/\.png$/i, ".json");
  const png = readFileSync(pngPath);
  const sidecar = JSON.parse(readFileSync(jsonPath, "utf8")) as Record<string, unknown>;
  const specs = (sidecar["roiSpecs"] as RoiSpec[] | undefined) ?? [];
  sidecar["measure"] = measureImage(png, undefined, edgeRect, specs);
  writeFileSync(jsonPath, JSON.stringify(sidecar, null, 2) + "\n");
  return sidecar;
}

const fmt = (n: number | null | undefined, d = 2): string => (n === null || n === undefined ? "n/a" : n.toFixed(d));

/** Generate `index.md` for a folder from its sidecars + measurements (replaces REVIEW.md, visual-target 6.6). */
export function generateIndexMd(dir: string, title = "Visual review capture index"): string {
  const sidecars = readdirSync(dir)
    .filter((f) => f.endsWith(".json") && !f.endsWith(".pathreport.json"))
    .sort()
    .map((f) => ({
      file: f.replace(/\.json$/, ".png"),
      s: JSON.parse(readFileSync(join(dir, f), "utf8")) as Record<string, unknown>,
    }));
  const lines = [
    `# ${title}`,
    "",
    "Generated by `tools/screenshots` (measure). Do not edit by hand. Verdicts (PASS/FAIL/N/A) and VT IDs are filled by visual-qa-reviewer.",
    "",
    "| VT ID | Verdict | File | Backend | Tier/preset | Size@DPR | Serve | Sun el | EV100 | Luma | Sobel | b* | Line edges 10-90 px | ROIs | Stars | Disk KB | Issue |",
    "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|",
  ];
  for (const { file, s } of sidecars) {
    const m = s["measure"] as MeasureResults | undefined;
    const sun = s["sun"] as { elevationDeg?: number } | null | undefined;
    const serve = s["serve"] as { mode?: string } | null | undefined;
    lines.push(
      `| - | N/A | ${file} | ${s["backend"] ?? "?"} | ${s["tier"] ?? "?"}/${s["preset"] ?? "?"} | ${s["width"] ?? "?"}x${s["height"] ?? "?"}@${s["dpr"] ?? "?"} | ` +
        `${serve?.mode ?? "?"} | ${fmt(sun?.elevationDeg, 1)} | ${fmt(s["ev100"] as number | null | undefined, 1)} | ` +
        `${fmt(m?.lumaMean.value, 1)} | ${fmt(m?.sobel.value)} | ${fmt(m?.labB.value)} | ${lineEdgeSummary(m)} | ${m?.rois ? Object.keys(m.rois).length : "n/a"} | ${m?.stars.value ?? "n/a"} | ` +
        `${m ? fmt(m.diskBytes / 1024, 0) : "n/a"} | - |`,
    );
  }
  lines.push("", `${sidecars.length} capture(s).`, "");
  const md = lines.join("\n");
  writeFileSync(join(dir, "index.md"), md);
  return md;
}
