// Golden vectors of the dust chunk payload (./dust-chunk). A codec must encode the described payload to exactly
// `length` bytes with CRC32 `crc32`, and to `bytesHex` where present. Changing a vector is a payload version change
// (DUST_CHUNK_PAYLOAD_VERSION).
//
// v1.1 (M1-W0-T08, additive): third vector "layout maximum", a chunk at exactly DUST_CHUNK_PAYLOAD_LAYOUT_MAX_BYTES
// (= DUST_CHUNK_PAYLOAD_MAX_BYTES). Its plots are generated by a fixed rule (below) instead of being listed. The stroke
// log bytes are an opaque pattern, not decodable chains: the payload layer does not read them.

import type { DustChunkGoldenVector } from "./dust-chunk";

/** Opaque stroke log of the layout-maximum vector: 576 bytes, byte i = (localIndex * 7 + i) & 0xff, as hex. */
function maxVectorStrokeLogHex(localIndex: number): string {
  let hex = "";
  for (let i = 0; i < 32 * 18; i += 1) hex += ((localIndex * 7 + i) & 0xff).toString(16).padStart(2, "0");
  return hex;
}

/** Plot k of the layout-maximum vector (every plot of chunk 41 touched, 4 contributions, 32 strokes of 18 B). */
function maxVectorPlot(k: number): DustChunkGoldenVector["plots"][number] {
  return {
    localIndex: k,
    remainingFrac: 255 - (k % 200),
    ledger: {
      version: k + 1,
      remainingUnits: 40_000 - k * 100,
      initialUnits: 40_000,
      ownedTexels: 1024 - (k % 600),
      mgPerUnit: 2480 + k,
      hash: Math.imul(k + 1, 0x9e37_79b1) >>> 0,
      contributions: [0, 1, 2, 3].map((c) => ({ actorSlot: c * 5 + (k % 5), units: k * 4 + c + 1 })),
    },
    texelsPattern: k % 2 === 0 ? "ramp" : "corners",
    strokeCount: 32,
    strokeLogHex: maxVectorStrokeLogHex(k),
  };
}

